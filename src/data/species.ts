/**
 * Realistic swim speeds: every species' hand-tuned cruise/burst is scaled by its PokeAPI
 * Speed stat — mult = 1 + 0.5 × (stat / 136) — so the whole reef swims quicker (nobody
 * slows down; Spheal +9%) while the genuinely fast feel fast (Barraskewda +50%).
 * 136 is the roster's top Speed stat (Barraskewda).
 */
const SWIM_STAT_TOP = 136;
for (const s of Object.values(SPECIES)) {
  const m = 1 + 0.5 * Math.min(1, s.fallbackStats.speed / SWIM_STAT_TOP);
  s.speed = Math.round(s.speed * m * 100) / 100;
  s.burst = Math.round(s.burst * m * 100) / 100;
}

export const SPECIES_LIST: SpeciesConfig[] = Object.values(SPECIES);

/**
 * Shiny variants live beside their species everywhere (collection, party) as `<id>__shiny` tokens.
 */
export const SHINY_SUFFIX = '__shiny';
export function isShinyToken(token: string): boolean { return token.endsWith(SHINY_SUFFIX); }
export function baseSpeciesId(token: string): string { return isShinyToken(token) ? token.slice(0, -SHINY_SUFFIX.length) : token; }
export function makeToken(speciesId: string, shiny: boolean): string { return shiny ? speciesId + SHINY_SUFFIX : speciesId; }
export function tokenLabel(token: string): string {
  const sp = SPECIES[baseSpeciesId(token)];
  return sp ? (isShinyToken(token) ? `Shiny ${sp.name}` : sp.name) : token;
}

export function getSpecies(id: string): SpeciesConfig {
  const s = SPECIES[id];
  if (!s) throw new Error(`Unknown species: ${id}`);
  return s;
}

/** Species in a behavior group (primary). */
export function speciesByGroup(group: SpeciesConfig['primary']): SpeciesConfig[] {
  return SPECIES_LIST.filter((s) => s.primary === group);
}

/** Returns the canonical guardian species id for a group member species, if any. */
export function guardianFor(speciesId: string): string | undefined {
  return SPECIES[speciesId]?.guardedBy?.[0];
}
